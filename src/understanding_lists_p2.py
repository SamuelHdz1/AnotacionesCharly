#AGREGANDO ELEMENTOS A UNA LISTA

motorcycles = ["honda", "mortalica", "yamaha"]
print(motorcycles)

"""
Para agregar elementos a una lista
metodo .append("kawasaki")

"""

#Método append
motorcycles.append("kawasaki")
print(motorcycles)

"""
El método append ayuda a crear listas fácilmente
de manera dinámica.
"""

motorcycles_2 = [] #lista vacía

print(motorcycles_2)

motorcycles_2.append("honda") # 1 elemento
motorcycles_2.append("yamaha") # 2 elemento
motorcycles_2.append("suzuki") # 3 elemento
print(motorcycles_2)
